## ============================================================
## Numbers behind the PCA text in the Results chapter
## ------------------------------------------------------------
## Writes  results final plots/data/pca_numbers (Sections 3.4-3.5).txt
## with every PCA value quoted in Sections 3.4 and 3.5: variance
## explained per principal component, and mean and standard deviation
## of the PC scores per group, for
##   - the full data set (Fig. 15a), by population
##   - the otoliths aged 1-3 years (Fig. 15b), by population
##   - the two-group comparisons (WBSS vs rest, BAS vs rest)
##   - the spawning groups
## The two-group comparisons and the spawning groups use the PCA of
## the full data set, as in the thesis.
##
## Same PCA as Fig. 15 (fig_pca.R): Momocs::PCA() on the Fourier
## coefficients in Results/eOTO.RData. For the age 1-3 subset the PCA is
## recomputed on the subset, and its axes are reversed where needed to
## match the full data set (the sign of a principal component is
## arbitrary).
## ============================================================

suppressPackageStartupMessages({ library(dplyr); library(Momocs) })

## ---- load project paths ------------------------------------
local({
  d <- normalizePath(getwd(), mustWork = FALSE)
  repeat {
    hit <- file.path(d, "config.R")
    hit <- hit[file.exists(hit)]
    if (length(hit)) { source(hit[1]); break }
    if (identical(dirname(d), d))
      stop("config.R not found -- please setwd() into the repository folder.",
           call. = FALSE)
    d <- dirname(d)
  }
})

RESULTS <- DIR_RESULTS
e <- new.env(); load(file.path(RESULTS, "eOTO.RData"), envir = e); eO <- e$eOTO

## ---- helpers ---------------------------------------------------
var_expl <- function(pc) 100 * pc$eig / sum(pc$eig)

## reverse an axis if its loadings run against the full-data axis
## (the same rule as in fig_pca.R)
align <- function(pc, ref) {
  flipped <- character(0)
  for (k in 1:2) if (cor(pc$rotation[, k], ref$rotation[, k]) < 0) {
    pc$x[, k] <- -pc$x[, k]; pc$rotation[, k] <- -pc$rotation[, k]
    flipped <- c(flipped, paste0("PC", k))
  }
  attr(pc, "flipped") <- flipped
  pc
}

out <- character(0)
add <- function(...) out <<- c(out, paste0(...))
f3  <- function(x) sprintf("%.3f", x)
f1  <- function(x) sprintf("%.1f", x)
fn  <- function(x) formatC(x, format = "d", big.mark = ",")

variance_block <- function(pc) {
  ve <- var_expl(pc)
  add("  Variance explained: ",
      paste(sprintf("PC%d %.1f%%", 1:5, ve[1:5]), collapse = ", "))
  add("  PC1 + PC2: ", f1(sum(ve[1:2])), "%   PC1 to PC5: ", f1(sum(ve[1:5])), "%")
}

group_block <- function(pc, g, lv) {
  d <- data.frame(PC1 = pc$x[, 1], PC2 = pc$x[, 2], g = factor(g, levels = lv))
  t <- d %>% group_by(g) %>%
    summarise(n = n(), m1 = mean(PC1), s1 = sd(PC1), m2 = mean(PC2), s2 = sd(PC2),
              .groups = "drop")
  add(sprintf("  %-15s %6s %7s %10s %8s %10s %8s", "Group", "n", "%", "mean PC1",
              "SD PC1", "mean PC2", "SD PC2"))
  for (i in seq_len(nrow(t)))
    add(sprintf("  %-15s %6s %7s %10s %8s %10s %8s", as.character(t$g[i]), fn(t$n[i]),
                f1(100 * t$n[i] / nrow(d)), f3(t$m1[i]), f3(t$s1[i]), f3(t$m2[i]), f3(t$s2[i])))
  add("  All otoliths: SD PC1 ", f3(sd(d$PC1)), ", SD PC2 ", f3(sd(d$PC2)))
  add("  Largest difference between two group means on PC1: ",
      f3(diff(range(t$m1))), " (", as.character(t$g[which.max(t$m1)]), " - ",
      as.character(t$g[which.min(t$m1)]), ")")
  invisible(t)
}

banner <- function(title) out <<- c(out, "", strrep("=", 70), title, strrep("=", 70), "")

add("PCA NUMBERS FOR THE RESULTS CHAPTER (Sections 3.4-3.5)")
add("Generated by 4 figures and tables/pca_numbers.R on ", format(Sys.Date(), "%d %b %Y"), ".")
add("Scores are PC scores of the otoliths; a group mean near 0 = average shape.")

## ---- full data set (Fig. 15a) ----------------------------------
pc_full <- PCA(eO)
banner(sprintf("FULL DATA SET, n = %s (Section 3.4, Fig. 15a)", fn(nrow(eO$coe))))
variance_block(pc_full)
add("")
group_block(pc_full, eO$fac$Assigned.Stock, POP_ORDER)

## ---- age 1-3 (Fig. 15b) ------------------------------------------
age <- suppressWarnings(as.numeric(as.character(eO$fac$Age)))
e13 <- Momocs::slice(eO, which(!is.na(age) & age >= 1 & age <= 3))
pc13 <- align(PCA(e13), pc_full)
banner(sprintf("OTOLITHS AGED 1-3 YEARS, n = %s (Section 3.4, Fig. 15b)", fn(nrow(e13$coe))))
add("  Own PCA of the subset; ",
    if (length(attr(pc13, "flipped")))
      paste(paste(attr(pc13, "flipped"), collapse = " and "),
            "reversed to match the full data set (as in the figure).")
    else "no axis needed reversing.")
variance_block(pc13)
add("")
group_block(pc13, e13$fac$Assigned.Stock, POP_ORDER)

## ---- two-group comparisons (PCA of the full data set) ------------
for (focal in c("WBSS", "BAS")) {
  g <- ifelse(eO$fac$Assigned.Stock == focal, focal, "Rest")
  banner(sprintf("%s VS REST (Section 3.5; PCA of the full data set)", focal))
  group_block(pc_full, g, c(focal, "Rest"))
}

## ---- spawning groups (PCA of the full data set) ------------------
banner("SPAWNING GROUPS (Section 3.5; PCA of the full data set)")
sp <- as.character(eO$fac$Spawning.Component)
t_sp <- group_block(pc_full, sp, c("spring spawner", "autumn spawner", "winter spawner"))
add("  Difference spring - autumn on PC1: ",
    f3(abs(diff(t_sp$m1[match(c("spring spawner", "autumn spawner"), t_sp$g)]))))

f <- file.path(ensure_dir(file.path(DIR_FINAL, "data")), "pca_numbers (Sections 3.4-3.5).txt")
writeLines(out, f)
cat(out, sep = "\n")
cat("\nwritten:", f, "\n")
